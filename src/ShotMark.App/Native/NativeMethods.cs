    /// <summary>Dunkle Titelleiste in der Farbe der Werkzeugleiste; ältere Windows-Versionen ignorieren das.</summary>
    public static void UseDarkTitleBar(System.Windows.Window window)
    {
        var hwnd = new System.Windows.Interop.WindowInteropHelper(window).Handle;
        if (hwnd == IntPtr.Zero) return;
        var enabled = 1;
        DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE, ref enabled, sizeof(int));
        var caption = 0x002E2A2A; // COLORREF 0x00BBGGRR = #2A2A2E
        DwmSetWindowAttribute(hwnd, DWMWA_CAPTION_COLOR, ref caption, sizeof(int));
    }

